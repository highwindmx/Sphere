// ====== 文字标注：每条河在折线中点加 label（随所在 group 一起显隐） ======
// 与 currents.js 同款写法：原先只有折线没有文字，球面上认不出哪条是哪条。
for (const g of LAYER.groups) {
  const labels = [];
  for (const e of g.entities) {
    if (e.type !== 'polyline' || !e.name || !Array.isArray(e.coords) || e.coords.length < 2) continue;
    // 取中段（略偏上游）作为标注锚点，避开入海口与首尾节点
    const m = e.coords[Math.max(0, Math.round(e.coords.length * 0.4))];
    labels.push({
      type: 'label',
      name: `${e.name} · 标注`,
      lon: m[0],
      lat: m[1],
      text: e.name,
    });
  }
  g.entities.push(...labels);
}
