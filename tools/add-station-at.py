def patch(fname, table):
    path = ROOT + fname
    src = io.open(path, encoding='utf-8').read()
    ok = 0
    for name, at in table:
        pat = "name: '%s',\n" % name
        cnt = src.count(pat)
        if cnt != 1:
            print('  !! %-24s 匹配 %d 次，跳过' % (name, cnt))
            continue
        src = src.replace(pat, "name: '%s',\n    at: '%s',\n" % (name, at))
        ok += 1
    io.open(path, 'w', encoding='utf-8').write(src)
    print('%-18s 补 %d/%d 站' % (fname, ok, len(table)))


