def geo_label(name, lon, lat):
    """返回 (大洲, 国家)。"""
    if name in NAME_FIX:
        return NAME_FIX[name]
    best = None
    for c, cont, a, b, cc, d in COUNTRY_RECT:
        if a <= lon <= cc and b <= lat <= d:
            area = (cc - a) * (d - b)
            if best is None or area < best[0]:
                best = (area, cont, c)
    if best:
        return best[1], best[2]
    for c, cont, a, b, cc, d in CONTINENT_RECT:
        if a <= lon <= cc and b <= lat <= d:
            return cont, c
    return "未知", "未知"


